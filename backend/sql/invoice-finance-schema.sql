-- =====================================================================
-- Billing, Finance, Company settings and Profile tables (PostgreSQL)
-- =====================================================================
-- You normally do NOT need this file: the app runs with
-- spring.jpa.hibernate.ddl-auto=update and creates these tables itself the
-- first time it starts. It is here for teams that prefer to create the
-- schema by hand (or review exactly what the entities map to).
--   psql -U postgres -d MainDatabase -f invoice-finance-schema.sql
-- Safe to run more than once (IF NOT EXISTS).

CREATE TABLE IF NOT EXISTS invoice (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(30)  NOT NULL UNIQUE,
    title           VARCHAR(255) NOT NULL,
    client          VARCHAR(255) NOT NULL,
    client_address  VARCHAR(500),
    client_phone    VARCHAR(40),
    client_email    VARCHAR(150),
    client_gstin    VARCHAR(30),
    issue_date      DATE         NOT NULL,
    due_date        DATE         NOT NULL,
    paid_date       DATE,
    status          VARCHAR(20)  NOT NULL CHECK (status IN ('PAID', 'UNPAID')),
    gst_rate        NUMERIC(5,2)  NOT NULL,
    discount        NUMERIC(14,2) NOT NULL,
    amount          NUMERIC(14,2) NOT NULL,
    notes           VARCHAR(2000),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS invoice_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT        NOT NULL REFERENCES invoice (id) ON DELETE CASCADE,
    line_no     INTEGER       NOT NULL,
    description VARCHAR(500)  NOT NULL,
    qty         NUMERIC(12,2) NOT NULL,
    rate        NUMERIC(14,2) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_invoice_item_invoice ON invoice_item (invoice_id);

CREATE TABLE IF NOT EXISTS finance_transaction (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_date       DATE          NOT NULL,
    description    VARCHAR(300)  NOT NULL,
    type           VARCHAR(20)   NOT NULL CHECK (type IN ('INCOME', 'EXPENSE')),
    category       VARCHAR(60)   NOT NULL,
    party          VARCHAR(150),
    payment_method VARCHAR(40),
    reference_no   VARCHAR(100),
    amount         NUMERIC(14,2) NOT NULL,
    status         VARCHAR(20)   NOT NULL CHECK (status IN ('COMPLETED', 'PENDING')),
    notes          VARCHAR(500),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_finance_txn_date ON finance_transaction (txn_date);

CREATE TABLE IF NOT EXISTS finance_budget (
    category      VARCHAR(60) PRIMARY KEY,
    monthly_limit NUMERIC(14,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS company_settings (
    id                  BIGINT PRIMARY KEY,
    name                VARCHAR(255),
    tagline             VARCHAR(255),
    address_line        VARCHAR(255),
    phone               VARCHAR(40),
    email               VARCHAR(150),
    gstin               VARCHAR(30),
    bank_account_name   VARCHAR(255),
    bank_name           VARCHAR(255),
    bank_account_number VARCHAR(40),
    bank_ifsc           VARCHAR(20),
    bank_upi            VARCHAR(80),
    terms               TEXT,
    default_gst         INTEGER,
    due_days            INTEGER,
    opening_balance     NUMERIC(14,2)
);

CREATE TABLE IF NOT EXISTS user_profile (
    user_id     BIGINT PRIMARY KEY,
    designation VARCHAR(80),
    location    VARCHAR(120),
    avatar      TEXT
);

-- Upgrading an existing database? (Hibernate's ddl-auto=update does this for you.)
ALTER TABLE invoice ADD COLUMN IF NOT EXISTS paid_date DATE;
-- Paid invoices created before paid_date existed: use the issue date as the best guess.
UPDATE invoice SET paid_date = issue_date WHERE status = 'PAID' AND paid_date IS NULL;
